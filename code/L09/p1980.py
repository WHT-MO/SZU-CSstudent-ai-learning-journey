# ============================================================
# 洛谷 P1980 计数问题（学员版，2026-09-13 洛谷 AC）
# 输入：一行两个整数 n x（0 ≤ x ≤ 9）
# 输出：一行一个整数 —— 1..n 的十进制写法里，数字 x 一共出现了多少次
#
# 核心决策（学员自产，从两次 TLE 改到 AC）：
#   ① 不攒中间容器：v1 把 1..n 的所有数字字符拼进一个列表再数（n = 10^6 时约
#      600 万元素 + 两趟遍历）→ 洛谷 TLE。改成"一趟遍历 + 计数器"，边扫边数、不存。
#   ② x 先 str 出循环：循环外 x = str(x)，循环里逐位做【字符比较】b == x，
#      不再每位 int(b)（本机 0.39s → 0.15s）。
#   ③ 让 C 实现干重活：同一题可 ''.join(...) + .count(...)（本机 0.09s），
#      本版未采用，保留最直观的逐位比较。
#
# 卡点记录：两次 TLE 才定位到"中间列表"是元凶；一度误以为"算法对就一定能过"。
# 已知边界：x = 0 也正确（实测输入 "1000000 0" → 488895，2026-09-14 复算一致）。
# ============================================================

z,x = map(int,input().split())
t = 0
x = str(x)
for a in range(1,z + 1):
    for b in str(a):
        if b == x:
            t = t + 1
print(t)
