# ============================================================
# 洛谷 P1420 最长连号（学员版，2026-09-13 洛谷 AC；2026-09-14 修 n = 1）
# 输入：第一行整数 n；第二行 n 个整数
# 输出：一行一个整数 —— 最长"连号"（后一个 = 前一个 + 1）连续段的长度
#
# 核心决策（学员自产）：
#   ① b = 0 时不能回头比 a[b-1]：a[-1] 是【负下标】，绕到最后一个元素，会把
#      "最后一个数 + 1 == 第一个数" 误判成"接着" → 用 b == 0 时 continue 跳掉本轮。
#   ② 两个变量分工：long = 当前段长（断了就归 1），max = 历史最长。
#   ③ n = 1 不需要单独分支：b = 0 被 continue 跳掉、循环体不跑，直接 print(max)，
#      而 max 初值就是 1 —— 正确答案本来就在默认值里（2026-09-14 学员自修）。
#
# 卡点记录：
#   ① 第一版没有 continue，靠 a[-1] 绕圈"碰巧 AC"；教员用构造用例 6 / "6 1 8 2 9 5"
#      挖出——真答案 1、程序输出 2。负下标合法、不报错，属于"不报错的错"。
#   ② 第二版想"跳过第一轮"却写了 break（撤整圈）→ n > 1 全部只输出 1；改
#      continue（跳本次）才对。速查卡 §6 坑 4 教过、考过，原样又撞上。
#   ③ 第三版把 n = 1 的处理写在循环体内（if n == 1: print(long)）→ n = 1 时循环里
#      打一次、循环外 print(max) 又打一次，输出两行。修法=删掉该分支：答案已由
#      max 初值给出，顺带消掉"判断留在循环里、每圈都白问一次"的问题。
#   另：变量名 max 覆盖了内置函数 max()（本题不用内置，暂无影响）。
#
# 实测验例（2026-09-14 复跑，8 组全过）：
#   n=1 "5" → 1 ｜ n=8 "1 2 3 5 6 7 8 10" → 4 ｜ n=5 "1 2 3 4 5" → 5
#   ｜ n=6 "6 1 8 2 9 5" → 1 ｜ n=2 "1 1" → 1 ｜ n=2 "1 2" → 2
#   ｜ n=3 "3 2 1" → 1 ｜ n=4 "1 2 2 3" → 2
# ============================================================

n = int(input())
a = list(map(int,(input().split())))
long = 1
max = 1
for b in range(n):
    if b == 0:
        continue
    elif a[b-1] + 1 == a[b]:
         long = long + 1
         if max < long:
            max = long
    else:
        long = 1
print(max)
