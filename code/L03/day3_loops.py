# ---- ① while：条件为真就一直做（倒计时） ----
i = 3
while i > 0:
    print(i)
    i = i - 1        # 计数器！忘了它 = 死循环
print("发射！")


# ---- ② for + range：数着来 ----
for n in range(1, 6):      # 1,2,3,4,5（前闭后开！不含6）
    print(n)

for even in range(2, 11, 2):   # 2,4,6,8,10（步长2）
    print(even)


# ---- ③ break / continue：刹车与跳步 ----
for day in range(1, 15):
    if day == 8:
        print("休整一天，跳过")
        continue              # 跳到下一次，不打印"第8天"
    if day == 13:
        print("提前收操")
        break                 # 整个循环结束
    print(f"军训第{day}天")


# ---- ④ 嵌套循环雏形（乘法表钥匙：外走一步，内走一圈） ----
for i in range(1, 4):
    for j in range(1, 4):
        print(i, j, end=" | ")   # end= 用竖线结尾，不换行
    print()                      # 内层一圈结束 → 换行


