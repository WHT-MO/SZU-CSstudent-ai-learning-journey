# ============================================================
# 洛谷 P5726 【深基4.习9】打分（学员版，2026-09-14 洛谷 AC）
# 输入：第一行 n；第二行 n 个整数（分值 0..10，3 ≤ n ≤ 1000）
# 输出：一行 —— 去掉一个最高分和一个最低分后的平均分，保留 2 位小数
#
# 核心决策（学员自产）：
#   ① 容器选 list，不选 set：set 无序、无下标（拿不出"首尾"），而且会【去重】——
#      本题分数会重复（样例里两个 9），要的是"保留重复 + 有序" → list。
#   ② 不排序也能去掉两端：总和 − max(scores) − min(scores) 天然等于"去掉一个最高
#      分 + 一个最低分"，重复最值也只减一个（4 4 4 → 12−4−4=4 ✓），分母 n − 2。
#   ③ 两位小数交给 f-string 格式说明符：f"{值:.2f}" 会补零；round 只管数值不管显示。
#
# 卡点记录：
#   ① 先想用 set + "删去首尾" → 撞上 set 无序（速查卡 L04L05 误区 5 / 自检题 4 已问过）；
#   ② 又试 dict{map(...)} → SyntaxError（dict 是函数、跟圆括号）；改成 dict(map(...))
#      仍 TypeError——dict 要的是"配对"，整数拆不出键值；本题也没有"键→值"的对应关系；
#   ③ 输出格式：第 3 次同类错（P1598 柱高格式 → P1428 输出成 n 行 → 今天小数位数），
#      但这次是【提交前自己发现的】，没等评测机打回来。
#
# 实测验例（2026-09-14 复跑，7 组全过）：
#   3/1 2 3 → 2.00 ｜ 5/9 5 6 8 9 → 7.67 ｜ 4/5 5 9 9 → 7.00 ｜ 3/4 4 4 → 4.00
#   ｜ 3/0 0 10 → 0.00 ｜ 3/2 4 6 → 4.00 ｜ 6/0 10 7 7 3 8 → 6.25
# ============================================================

n = int(input())
scores = list(map(int,input().split()))
t = 0
for x in scores:
    t = t + x
total = t - max(scores) - min(scores)
print(f"{total / (n - 2):.2f}")
