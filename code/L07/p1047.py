# ============================================================
# 洛谷 P1047 校门外的树（学员版，2026-09-11 洛谷 AC）
# 输入：第一行 l m；随后 m 行，每行 u v（移走 [u, v] 区间内的树，含两端）
# 输出：一行一个整数 —— 移完后剩余的树数
#
# 核心决策（学员自产）：
#   位置就是数据 —— 用 "每格一个状态" 记马路：0=有树、1=已移走。只改状态，绝不删元素
#   （删元素会让后面的格子整体前移，位置编号失真）。
#   区间重合因此自动消失：同一格被赋 1 两次，结果一样，代码里无需任何"判重/合并"。
# 收数：trees.count(0) = 还剩几格有树。
#
# 卡点记录：想过用 list.append 逐个建表（未采用）、想过"从列表移除区域"（结论=不该删）。
# 已知边界：l ≤ 10^4、m ≤ 100；题目保证 0 ≤ u ≤ v ≤ l（无需处理反向区间）。
# ============================================================

l, m = map(int, input().split())
l = l + 1
trees = [0] * l
for _ in range(m):
    u, v = map(int, input().split())
    for x in range(u, v + 1):
        trees[x] = 1
print(trees.count(0))
