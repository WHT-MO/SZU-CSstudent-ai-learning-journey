# ============================================================
# 洛谷 P1428 小鱼比可爱（学员版，2026-09-12 洛谷 AC）
# 输入：第一行 n；第二行 n 个非负整数（可爱程度，可能相同）
# 输出：一行 n 个整数，空格隔开，依次是"每只鱼左边比它小的鱼的个数"
#
# 核心思路（学员自产）：逐只鱼回头扫左边
#   外层：for x 遍历每只鱼；内层：for _ in range(x) 只扫 x 左边那 x 只
#   比较：line[y] < line[x]  ← 【左边比我小】才算（相等不算，`>=` 会把它算进去）
#   收数：fish = [0] * n 造表，命中就 fish[x] + 1
#
# 卡点记录：
#   ① 比较方向写反（line[x] >= line[y]）→ 全等值测例会暴露；
#   ② 打印误放进外层循环 → 输出成 n 行（题目要一行）；
#   ③ " ".join(words[x]) 把单个元素喂给 join → join 会拆字符（" ".join("abc") = "a b c"）。
#   join 复习：分隔符在前（" ".join(...)），括号里放整串文字；join 只吃文字 → 先 str()。
#
# 已知小冗点：第 10 行 words 的构造仍在外层循环体内（每圈重建整个文字列表），
#   跑得对但白干 n-1 次；下次可移到与 print 同级。
# ============================================================

nums = int(input())
line = list(map(int,input().split()))
fish = [0] * nums
for x in range(0,nums):
    y = x - 1
    for _ in range(x):
        if line[y] < line[x]:
            fish[x] = fish[x] + 1
        y = y - 1
    words = list(map(str,fish))
print(" ".join(words))
