# 洛谷 P5711 闰年判断（学员原稿，2026-09-07 首次 AC 100 分）
# 输入：一个年份（一行整数）
# 输出：1 = 闰年，0 = 平年
#
# 出处：从 code\L02\my_day2.py 第 29–34 行**原样抽出**
#      （2026-09-20 学员授权补入库，代码未做任何改动）
# 判据：能被 4 整除且不能被 100 整除，或者能被 400 整除
# ============================================================

year=int(input())
if (year%4==0 and year%100!=0) or (year%400==0):
    print(1)  #闰年
else:
    print(0)  #平年
