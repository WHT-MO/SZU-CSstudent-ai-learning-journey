# ---- ① 成绩等级判断器（elif 链） ----
score = int(input("输入成绩(0-100): "))
if score >= 90:
    print("A")
elif score >= 80:
    print("B")
elif score >= 70:
    print("C")
elif score >= 60:
    print("D")
else:
    print("不及格")


# ---- ② 闰年判断（今晚 OJ 题 P5711，输出 1/0） ----
# 规则：四年一闰，百年不闰，四百年再闰
year = int(input("输入年份: "))
if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    print(1)      # 闰年
else:
    print(0)      # 平年

# 自测：1900→0  2000→1  2024→1  2026→0
