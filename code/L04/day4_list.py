# ---- ① 列表基础：一个盒子装一串 ----
scores = [85, 92, 78, 90]
print(scores)        # [85, 92, 78, 90]
print(scores[0])     # 85（第 0 个！）
print(scores[3])     # 90
print(scores[-1])    # 90（倒数第 1 个）
print(len(scores))   # 4

nums = []            # 空列表
nums.append(10)      # 尾部追加
nums.append(20)
nums[0] = 99         # 修改
print(nums)          # [99, 20]

for n in nums:       # 遍历：逐个拿出来
    print(n)

print(scores[1:3])   # 切片 [92, 78]（前闭后开）


