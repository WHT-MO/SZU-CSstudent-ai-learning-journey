# ---- 1. print：让程序说话 ----
print("hello, szu")
print("我是深大计软大一新生")
print(1 + 1)            # 数字不用引号
print("答案是", 1 + 1)   # 英文逗号分隔，一次打印多个

# ---- 2. 变量：给数据起名字 ----
name = "张三"           # str   字符串
age = 18               # int   整数
height = 1.75          # float 小数
is_student = True      # bool  真/假
print(name, age, height)

age = age + 1          # 盒子内容可以改：读作"加1再存回age"
print("长一岁后", age)

print(type(name))      # <class 'str'> 查看类型

# ---- 3. input：让程序听你说话 ----
name = input("你叫什么名字？")
print("你好，" + name)

age = input("你多大了？")   # input 永远返回字符串
age = int(age)             # 转换器：字符串 -> 整数
print("明年你", age + 1, "岁")

# ---- 4. f-string：推荐的拼接方式 ----
college = input("你是哪个学院的？")
print(f"你好，{name}！欢迎来到{college}")


